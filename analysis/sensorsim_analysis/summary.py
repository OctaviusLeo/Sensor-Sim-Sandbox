"""summary.py — writes the generated ``results/summary.md`` consumed by the README.

The Summary_File is generated, never hand-edited; two runs on identical inputs yield
bitwise-identical numeric results (Requirement 8.6, 8.8, 0.1). Numbers are formatted
with fixed precision, and the file is written to a temporary name and renamed only once
it is complete, so a failed analysis never leaves a Summary_File behind.
"""

from __future__ import annotations

import math
import os
from dataclasses import dataclass
from pathlib import Path

from .metrics import SensorMetrics

RATE_TARGET_HZ = 10.0  # used for a topic whose sensor has no configured rate_hz

# Sensor whose configured rate_hz is the target for each published topic.
TOPIC_SENSOR = {
    "/lidar/points": "lidar",
    "/camera/image/compressed": "camera",
    "/imu": "imu_accel",
    "/gps/fix": "gps",
}


@dataclass
class RateMeasurement:
    """A measured publish rate with its provenance."""

    topic: str
    rate_hz: float
    source: str  # e.g. "ros2 topic hz (60 s)" or "bag timestamps"


def fmt(x: float | int | None, digits: int = 6) -> str:
    if x is None:
        return "n/a"
    if isinstance(x, int):
        return str(x)
    if math.isnan(x):
        return "n/a"
    return f"{x:.{digits}f}"


def rate_target_hz(topic: str, metrics: dict[str, SensorMetrics]) -> float:
    """Configured rate of the sensor behind ``topic``; RATE_TARGET_HZ if it has none."""
    m = metrics.get(TOPIC_SENSOR.get(topic, ""))
    if m is not None and m.configured_rate_hz:
        return float(m.configured_rate_hz)
    return RATE_TARGET_HZ


def render_summary(
    metrics: dict[str, SensorMetrics],
    *,
    command: str,
    seed: int | None,
    commit: str | None,
    run_log: str,
    rates: list[RateMeasurement] | None = None,
    notes: list[str] | None = None,
) -> str:
    lines = [
        "# Sensor Sim Sandbox — results summary",
        "",
        "Generated by `analysis/analyze.py`; do not edit by hand.",
        "",
        f"- Command: `{command}`",
        f"- Seed: {seed if seed is not None else 'n/a'}",
        f"- Commit: `{commit or 'n/a'}`",
        f"- Run_Log: `{run_log}`",
        "",
        "## Per-sensor metrics",
        "",
        "| Sensor | Bias | Configured bias | Std | RMSE | Error samples | Configured noise σ "
        "| Measured dropout | Configured dropout | Measured latency (ms) "
        "| Configured latency (ms) | Achieved rate (Hz) | Published |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in sorted(metrics):
        m = metrics[name]
        lines.append(
            f"| {m.sensor} | {fmt(m.bias)} | {fmt(m.configured_bias, 4)} | {fmt(m.std)} | {fmt(m.rmse)} | {m.error_samples} "
            f"| {fmt(m.configured_noise_sigma, 4)} | {fmt(m.measured_dropout)} "
            f"| {fmt(m.configured_dropout, 4)} | {fmt(m.measured_latency_ms, 3)} "
            f"| {fmt(m.configured_latency_ms, 1)} | {fmt(m.achieved_rate_hz, 4)} "
            f"| {m.published_count} |"
        )
    lines += [
        "",
        "Units: lidar and gps error in meters, imu_accel in m/s², imu_gyro in rad/s, "
        "camera error in 8-bit intensity levels "
        "(sampled frames, published JPEG vs truth PNG, so JPEG compression error is included). "
        "Rate is `(n - 1) / T` over `t_publish`.",
    ]
    if rates:
        lines += [
            "",
            "## Measured ROS 2 publish rates (target: each sensor's configured rate)",
            "",
            "| Topic | Measured rate (Hz) | Target (Hz) | Met | Source |",
            "| --- | --- | --- | --- | --- |",
        ]
        for r in rates:
            target = rate_target_hz(r.topic, metrics)
            met = "n/a" if math.isnan(r.rate_hz) else ("yes" if r.rate_hz >= target else "no")
            lines.append(
                f"| `{r.topic}` | {fmt(r.rate_hz, 3)} | {target:g} | {met} | {r.source} |"
            )
    if notes:
        lines += ["", "## Notes", ""] + [f"- {n}" for n in notes]
    return "\n".join(lines) + "\n"


def write_summary(path: str | Path, text: str) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, p)
    return p
